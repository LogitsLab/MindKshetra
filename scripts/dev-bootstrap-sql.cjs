#!/usr/bin/env node
/**
 * Emit every migration as one SQL script, in order, for bootstrapping a fresh
 * Supabase project (e.g. MindKshetra-dev) through the dashboard SQL editor
 * when no CLI access token is configured. With the CLI linked, prefer:
 *
 *   npx supabase link --project-ref <ref> && npx supabase db push
 *
 * Usage: node scripts/dev-bootstrap-sql.cjs            # to stdout
 *        node scripts/dev-bootstrap-sql.cjs | pbcopy   # straight to clipboard
 *
 * Safe to re-run on a project that already has some migrations: every
 * statement in this repo's migrations is written idempotently
 * (create ... if not exists / drop policy if exists / add column if not exists).
 */
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "..", "supabase", "migrations");
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

process.stdout.write(
  `-- MindKshetra schema bootstrap (${files.length} migrations)\n` +
    `-- Generated by scripts/dev-bootstrap-sql.cjs — do not edit by hand.\n\n`
);

for (const file of files) {
  process.stdout.write(`\n-- ========== ${file} ==========\n\n`);
  process.stdout.write(fs.readFileSync(path.join(dir, file), "utf8"));
  process.stdout.write("\n");
}
